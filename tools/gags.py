"""反覆用的小梗：寫手很容易章章都用一遍（第 4–6 章「忘帶打火機零遞火」連用三章）。

check.py 拿這一章和上一章比，連著出現就報；compose.py 把上一章用過的列給寫手。
一行一個：梗的說法 → 正則。新發現章章都在用的梗，往這裡加一行。
"""
import re

GAGS = {
    '找打火機讓零遞火': r'打火機',
    '不加糖的熱飲': r'不加糖|沒加糖|無糖',
    '芬格爾借錢蹭飯': r'芬格爾[^\n]{0,80}(?:借|請客|請你|蹭|欠)',
    '從零食或零花錢裡扣': r'扣[^。\n]{0,6}(?:零食|零花錢)|(?:零食|零花錢)[^。\n]{0,8}(?:裡扣|扣)',
    '實戰課打幾環混及格': r'[四五六七]環',
    '長蘑菇': r'長蘑菇',
    '塞薄荷糖': r'薄荷糖',
    '暈船暈車': r'暈船|暈車',
    '論壇開盤口賭子航': r'盤口|開盤',
}


def found(text):
    return [name for name, pattern in GAGS.items() if re.search(pattern, text)]
